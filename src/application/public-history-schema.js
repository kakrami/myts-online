/** Explicit, bounded public history requests. These are not team connections. */
export const PUBLIC_HISTORY_SCHEMA=[
  `CREATE TABLE public_history_demands(
    id TEXT PRIMARY KEY,
    app_team_id TEXT NOT NULL REFERENCES app_teams(id) ON DELETE CASCADE,
    team_season_id TEXT NOT NULL REFERENCES team_seasons(id) ON DELETE CASCADE,
    event_id TEXT NOT NULL REFERENCES events(id),
    source_event_id TEXT NOT NULL REFERENCES source_events(id),
    home_source_team_id TEXT NOT NULL REFERENCES source_teams(id),
    away_source_team_id TEXT NOT NULL REFERENCES source_teams(id),
    pair_a TEXT NOT NULL REFERENCES source_teams(id),
    pair_b TEXT NOT NULL REFERENCES source_teams(id),
    anchor_attachment_id TEXT NOT NULL REFERENCES team_source_attachments(id) ON DELETE CASCADE,
    anchor_generation INTEGER NOT NULL CHECK(anchor_generation>0),
    anchor_kind TEXT NOT NULL CHECK(anchor_kind IN('own','division')),
    anchor_membership_id TEXT,
    requester_kind TEXT NOT NULL CHECK(requester_kind IN('owner','viewer')),
    requester_key TEXT NOT NULL,
    generation INTEGER NOT NULL DEFAULT 1 CHECK(generation>0),
    state TEXT NOT NULL DEFAULT 'active' CHECK(state IN('active','complete','partial','failed','expired','revoked')),
    requested_at INTEGER NOT NULL,
    expires_at INTEGER NOT NULL,
    cooldown_until INTEGER NOT NULL,
    max_jobs INTEGER NOT NULL DEFAULT 512 CHECK(max_jobs BETWEEN 2 AND 512),
    capped INTEGER NOT NULL DEFAULT 0 CHECK(capped IN(0,1)),
    CHECK(home_source_team_id<>away_source_team_id),
    CHECK(pair_a<pair_b AND ((pair_a=home_source_team_id AND pair_b=away_source_team_id) OR(pair_a=away_source_team_id AND pair_b=home_source_team_id))),
    CHECK((anchor_kind='own' AND anchor_membership_id IS NULL) OR(anchor_kind='division' AND anchor_membership_id IS NOT NULL)),
    CHECK(requester_kind<>'owner' OR requester_key='owner'),
    CHECK(expires_at>requested_at AND expires_at-requested_at<=86400000),
    UNIQUE(app_team_id,team_season_id,requester_kind,requester_key,pair_a,pair_b)
  )`,
  `CREATE INDEX public_history_demands_team ON public_history_demands(app_team_id,state,expires_at)`,
  `CREATE TABLE public_history_jobs(
    demand_id TEXT NOT NULL REFERENCES public_history_demands(id) ON DELETE CASCADE,
    generation INTEGER NOT NULL CHECK(generation>0),
    job_id TEXT NOT NULL,
    accepted_scan_id TEXT NOT NULL,
    parent_job_id TEXT,
    root_source_team_id TEXT NOT NULL,
    provider TEXT NOT NULL CHECK(provider IN('gotsport','live')),
    component TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending' CHECK(state IN('pending','complete','failed','superseded')),
    accepted_at INTEGER NOT NULL,
    completed_at INTEGER,
    PRIMARY KEY(demand_id,generation,job_id)
  )`,
  `CREATE INDEX public_history_jobs_work ON public_history_jobs(job_id,accepted_scan_id,state,demand_id,generation)`,
];
